#!/usr/bin/env node
/**
 * Generate the API-side copy of the fork's readonly memory tool projection.
 *
 * The API package must not import the MCP server at runtime (the server owns
 * Node/MCP dependencies the API does not ship). The Qoder init gate therefore
 * consumes a generated static artifact, and its freshness is locked by
 * packages/api/test/qoder-l2-tool-surface.test.js.
 *
 * The projection source is the canonical registry itself:
 *   buildMemoryTools({ readonly: true, callbackCredentials: false })
 *
 * `callbackCredentials: false` is the explicit Qoder memory-shim capability
 * declaration: the shim receives identity vars only, never callback
 * credentials. Tools whose only authorization path is a callback (recall
 * metrics, meeting artifacts) must not be advertised there.
 *
 * Usage:
 *   node scripts/generate-fork-memory-projection.mjs           # write
 *   node scripts/generate-fork-memory-projection.mjs --check   # fail on drift
 *   node scripts/generate-fork-memory-projection.mjs --stdout  # print
 *
 * Requires packages/mcp-server/dist (run its build first).
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT_PATH = resolve(ROOT, 'packages', 'api', 'src', 'generated', 'fork-memory-tools.ts');
const MCP_DIST = resolve(ROOT, 'packages', 'mcp-server', 'dist', 'server-toolsets.js');

export const GENERATED_HEADER = [
  '// Generated by scripts/generate-fork-memory-projection.mjs — do not edit by hand.',
  '// Source: buildMemoryTools({ readonly: true, callbackCredentials: false })',
  '// from the canonical MCP tool registry. Regenerate after changing the registry.',
].join('\n');

export async function buildProjection() {
  if (!existsSync(MCP_DIST)) {
    throw new Error(
      `Missing ${MCP_DIST}. Build @cat-cafe/mcp-server first (pnpm --filter @cat-cafe/mcp-server build).`,
    );
  }
  const mcp = await import(MCP_DIST);
  const tools = mcp.buildMemoryTools({ readonly: true, callbackCredentials: false });
  const names = [...new Set(tools.map((tool) => tool.name))].sort();
  if (names.length === 0) {
    throw new Error('Canonical readonly memory projection is empty — refusing to generate an empty allowlist.');
  }
  return names;
}

export function renderProjection(names) {
  return [
    GENERATED_HEADER,
    '// The count is derived from the registry; never pin a literal length here.',
    'export const QODER_READONLY_MEMORY_TOOLS = Object.freeze([',
    ...names.map((name) => `  '${name}',`),
    '] as const);',
    '',
  ].join('\n');
}

async function main() {
  const names = await buildProjection();
  const rendered = renderProjection(names);
  if (process.argv.includes('--stdout')) {
    process.stdout.write(rendered);
    return;
  }
  if (process.argv.includes('--check')) {
    if (!existsSync(OUTPUT_PATH)) throw new Error(`Missing generated projection: ${OUTPUT_PATH}`);
    const current = readFileSync(OUTPUT_PATH, 'utf8');
    if (current !== rendered) {
      throw new Error(
        `Generated fork memory projection is stale: ${OUTPUT_PATH}\n` +
          'Run `pnpm generate:fork-memory-projection` and commit the result.',
      );
    }
    process.stdout.write(`fork memory projection up to date (${names.length} tools)\n`);
    return;
  }
  writeFileSync(OUTPUT_PATH, rendered, { encoding: 'utf8' });
  process.stdout.write(`wrote ${OUTPUT_PATH} (${names.length} tools)\n`);
}

const invokedPath = process.argv[1] ? resolve(process.argv[1]) : '';
if (invokedPath === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  });
}
